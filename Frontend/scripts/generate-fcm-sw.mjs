import { readFileSync, writeFileSync, existsSync, mkdirSync, copyFileSync } from "node:fs"
import { resolve, dirname } from "node:path"
import { fileURLToPath } from "node:url"

const cwd = process.cwd()
const scriptDir = dirname(fileURLToPath(import.meta.url))
const scriptRoot = resolve(scriptDir, "..")
const root = existsSync(resolve(cwd, "public"))
  ? cwd
  : existsSync(resolve(cwd, "Frontend", "public"))
  ? resolve(cwd, "Frontend")
  : scriptRoot
const envPath = resolve(root, ".env.local")
const outPath = resolve(root, "public", "firebase-messaging-sw.js")

const sdkDir = resolve(root, "public", "firebase")
const appCompatSrc = resolve(root, "node_modules", "firebase", "firebase-app-compat.js")
const msgCompatSrc = resolve(root, "node_modules", "firebase", "firebase-messaging-compat.js")
const appCompatDest = resolve(sdkDir, "firebase-app-compat.js")
const msgCompatDest = resolve(sdkDir, "firebase-messaging-compat.js")

const requiredKeys = [
  "NEXT_PUBLIC_FIREBASE_API_KEY",
  "NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN",
  "NEXT_PUBLIC_FIREBASE_PROJECT_ID",
  "NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET",
  "NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID",
  "NEXT_PUBLIC_FIREBASE_APP_ID",
]

function parseEnv(content) {
  const result = {}
  const lines = content.split(/\r?\n/)
  for (const line of lines) {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith("#")) continue
    const eqIndex = trimmed.indexOf("=")
    if (eqIndex === -1) continue
    const key = trimmed.slice(0, eqIndex).trim()
    let value = trimmed.slice(eqIndex + 1).trim()
    if (value.startsWith("\"") && value.endsWith("\"")) {
      value = value.slice(1, -1)
    }
    if (value.startsWith("'") && value.endsWith("'")) {
      value = value.slice(1, -1)
    }
    result[key] = value
  }
  return result
}

const envFromFile = existsSync(envPath) ? parseEnv(readFileSync(envPath, "utf8")) : {}
const env = { ...envFromFile, ...process.env }

const missing = requiredKeys.filter((key) => !env[key])
if (missing.length) {
  console.error(`[FCM SW] Missing env keys: ${missing.join(", ")}`)
  process.exit(1)
}

const hasLocalCompat = existsSync(appCompatSrc) && existsSync(msgCompatSrc)
if (hasLocalCompat) {
  mkdirSync(sdkDir, { recursive: true })
  copyFileSync(appCompatSrc, appCompatDest)
  copyFileSync(msgCompatSrc, msgCompatDest)
} else {
  console.warn("[FCM SW] Firebase compat SDK files not found. Falling back to CDN importScripts.")
}

const compatBase = hasLocalCompat
  ? "/firebase"
  : "https://www.gstatic.com/firebasejs/10.12.5"

const content = `/* eslint-disable no-undef */
/* global firebase */
// AUTO-GENERATED by scripts/generate-fcm-sw.mjs
importScripts("${compatBase}/firebase-app-compat.js")
importScripts("${compatBase}/firebase-messaging-compat.js")

firebase.initializeApp({
  apiKey: "${env.NEXT_PUBLIC_FIREBASE_API_KEY}",
  authDomain: "${env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN}",
  projectId: "${env.NEXT_PUBLIC_FIREBASE_PROJECT_ID}",
  storageBucket: "${env.NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET}",
  messagingSenderId: "${env.NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID}",
  appId: "${env.NEXT_PUBLIC_FIREBASE_APP_ID}",
})

const messaging = firebase.messaging()

messaging.onBackgroundMessage((payload) => {
  const title = payload?.notification?.title || "새 알림"
  const options = {
    body: payload?.notification?.body || "",
    icon: "/icons/icon-192.png",
    data: payload?.data ?? {},
  }

  self.registration.showNotification(title, options)
})

self.addEventListener("notificationclick", (event) => {
  event.notification.close()
  const detectionId = event.notification?.data?.detectionId
  const targetUrl = detectionId ? "/dashboard?detectionId=" + detectionId : "/dashboard"

  event.waitUntil(
    self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((clientList) => {
      for (const client of clientList) {
        if ("focus" in client) {
          client.navigate(targetUrl)
          return client.focus()
        }
      }
      if (self.clients.openWindow) {
        return self.clients.openWindow(targetUrl)
      }
      return undefined
    })
  )
})
`

mkdirSync(resolve(root, "public"), { recursive: true })
writeFileSync(outPath, content, "utf8")
console.log("[FCM SW] Generated public/firebase-messaging-sw.js")
